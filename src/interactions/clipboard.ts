/**
 * A position-independent snapshot of copied musical material.
 *
 * Built to grow with the selection: `events` is the note/chord/tuplet section
 * (the only one today); future element kinds (dynamics, clefs, …) become their own
 * optional sections, dispatched on paste the same way the {@link SelectionItem}
 * union is. `version` guards the shape for forward-compat / OS-clipboard JSON.
 *
 * No model ids are stored — pitches/events carry none, ties are regenerated by the
 * rebar relay on paste, and tuplets travel as atomic payloads. That is what makes
 * a payload safely re-pasteable any number of times.
 */
/**
 * One copied lane: a `(staff, voice)` pair and its event stream. The staff is a
 * RELATIVE index (0 = topmost copied staff) so a clip spanning staves 1+2 can land
 * on staves 3+4 — paste adds the paste-target staff to it (payload v3, docs/copy-paste-staff-plan.md).
 */
export interface ClipboardLane {
  /** RELATIVE staff index within the clip (0 = topmost copied staff). Paste maps it to
   *  `targetStaff + staff`, clamped to the score's staff count. */
  staff: number
  /** Model voice number (0-based). */
  voice: number
  /**
   * The rhythmic stream for this lane, offsets relative to the selection start
   * (quarter beats). Internal ties are collapsed into single logical notes;
   * tuplets are atomic. Unselected gaps are implicit — rest-filled on paste.
   */
  events: RebarEvent[]
  /**
   * Manual rest shifts inside the selection window, offsets relative to the selection
   * start (same basis as {@link events}) so they re-base by the paste start. Carried
   * separately because rests are not events — a shifted rest must travel even though it
   * produces no note. Absent/empty = no shifted rests. See docs/rest-shift-plan.md §6.5.
   */
  restShifts?: Array<{ offset: Fraction; steps: number }>
  /**
   * Hidden rests inside the selection window, offsets relative to the selection start
   * (same basis as {@link events}). Carried separately for the same reason as
   * {@link restShifts} — a hidden rest produces no note but must travel. Absent/empty =
   * none hidden. See docs/rest-hide-plan.md.
   */
  restHidden?: Array<{ offset: Fraction }>
  /**
   * Note horizontal offsets (client #12) inside the selection window, offsets relative to the
   * selection start (same basis as {@link events}). Carried separately because the override is
   * SLOT-keyed and nothing in `events` (which holds no ids) can drag it along — a copied passage
   * would otherwise arrive un-offset. Covers chords AND rests (a note offset hangs off the slot).
   * Absent/empty = none. See docs/note-offset-plan.md.
   *
   * ⭐ `member` is a fanned MEMBER's place in its group (1…count−1), absent for the slot itself: the
   * member's own offset travels with the group it belongs to, addressed by index because the paste
   * mints fresh member ids.
   */
  noteOffsets?: Array<{ offset: Fraction; x: number; member?: number }>
  /**
   * Two-note tremolos whose BOTH notes are inside the selection window, at the FIRST note's offset
   * relative to the selection start (same basis as {@link events}).
   *
   * ⭐ Carried separately for the reason {@link restShifts} and {@link noteOffsets} are, and it is the
   * sharpest case of it: `RebarEvent` deliberately has NO `tremoloPair` field, because the relay
   * copies a split event's marks to every piece and a pair minted on each half of a tie-split would
   * be a bogus mark between two halves of one note (docs/two-note-tremolo-plan.md §1). That drop is
   * right for a RE-BAR, where adjacency genuinely may not survive — and wrong for a COPY, which
   * carries both notes and can simply reproduce the mark. So the relay stays clean and the clip
   * carries the relation itself.
   *
   * ⚠️ Only pairs whose PARTNER is also in the window travel: half a mark is not a mark. Re-validated
   * on paste against the tiling that actually arrives.
   */
  tremoloPairs?: Array<{ offset: Fraction; style?: 'joined' | 'open' }>
}

/**
 * A dynamic marking captured inside the copy window, re-anchored on paste. Staff is a
 * RELATIVE index (0 = topmost copied staff), like {@link ClipboardLane.staff}; `offset` is
 * relative to the selection start (quarter beats). Only dynamics whose position is FULLY
 * inside the window travel (decision: fully-enclosed-only). See docs/copy-paste-staff-plan.md.
 */
export interface ClipDynamic {
  /** RELATIVE staff index (0 = topmost copied staff). Paste maps it to `targetStaff + staff`. */
  staff: number
  /** Governed voice (0-based). */
  voice: number
  /** Beat offset from the selection start (same basis as {@link ClipboardLane.events}). */
  offset: Fraction
  /** The mark's whole text (SMuFL glyphs + words) — the level travels inside it. See {@link Dynamic.text}. */
  text: string
  placement?: 'above' | 'below'
  /** Hand-nudged engraving offset (client #8), captured at copy so it travels with the mark. */
  engravingOffset?: { x: number; y: number }
}

/** A pitch identity used to re-find a slur endpoint on the pasted notes. */
interface ClipSlurPitch { step: string; alter: number; octave: number }

/**
 * A slur captured inside the copy window, re-anchored on paste (Phase 3). Both endpoints are
 * addressed by RELATIVE staff (0 = topmost copied staff), voice, clip-relative offset, and
 * pitch — so paste re-finds the freshly-pasted note that now sits at that position. Only slurs
 * with BOTH endpoints fully inside the window travel (decision: fully-enclosed-only).
 */
export interface ClipSlur {
  startStaff: number; startVoice: number; startOffset: Fraction; startPitch: ClipSlurPitch
  endStaff: number;   endVoice: number;   endOffset: Fraction;   endPitch: ClipSlurPitch
  placement?: 'above' | 'below'
}

export interface ClipboardPayload {
  format: 'opus-editor/clipboard'
  version: 3
  /** Where it was copied from (reference / debugging only). */
  origin: { measure: number; beat: Fraction }
  /** Total covered length, in quarter-note beats. */
  spanBeats: Fraction
  /** Number of staves the selection covered (for clamp math / UX). 1 for a single-staff clip. */
  spanStaves: number
  /**
   * One entry per `(staff, voice)` lane that contained a selected note, with the staff
   * stored as a RELATIVE index (0 = topmost copied staff). A single-voice clip is
   * re-voiced into the paste target voice; a multi-voice clip preserves each voice.
   * Lanes are stored as an array (not a Map) to stay JSON-serializable.
   */
  lanes: ClipboardLane[]
  /** Dynamics fully inside the copy window, re-anchored on paste (Phase 2). Absent/empty = none. */
  dynamics: ClipDynamic[]
  /** Slurs fully inside the copy window, re-anchored on paste (Phase 3). Absent/empty = none. */
  slurs: ClipSlur[]
  /**
   * User-authored horizontal spaces (client #10) whose column falls inside the copy window,
   * offsets relative to the selection start (same basis as {@link ClipboardLane.events}).
   *
   * **Top-level, not per lane** — the one piece of this payload that is neither, and deliberately:
   * a space belongs to the COLUMN, not to a note in it, so it has no voice and no staff to carry.
   * That makes it the simplest thing here to re-base and the only one paste maps by offset alone.
   *
   * Carried at all for the same reason `restShifts` is: the override is position-keyed, so nothing
   * in `events` can drag it along, and a copied passage would silently arrive unspaced.
   * Absent/empty = none. See docs/note-spacing-plan.md §6.
   */
  spaces?: Array<{ offset: Fraction; space: number }>
  // future: clefs?: ClipboardClef[]; ...
}

/** Cumulative quarter-beat offset of each measure's start, keyed by measure number. */
function measureStartOffsets(score: Score): Map<number, Fraction> {
  const out = new Map<number, Fraction>()
  let base = fracCreate(0, 1)
  for (const m of [...score.measures].sort((a, b) => a.number - b.number)) {
    out.set(m.number, base)
    base = fracAdd(base, measureCapacityFrac(m))
  }
  return out
}

/** The sounding span [absStart, absEnd) of every selected flat note, in quarter beats. */
function selectedSpans(score: Score, noteIds: Set<string>): { start: Fraction; end: Fraction }[] {
  const starts = measureStartOffsets(score)
  const spans: { start: Fraction; end: Fraction }[] = []
  for (const m of score.measures) {
    const mStart = starts.get(m.number)
    if (!mStart) continue
    for (const n of getMeasureNotes(m)) {
      if (!noteIds.has(n.id)) continue
      const dur = slotLength(n)
      const start = fracAdd(mStart, n.beat)
      spans.push({ start, end: fracAdd(start, dur) })
    }
  }
  return spans
}

/**
 * Manual rest shifts of one `(staff, voice)` lane whose rest onset falls inside the copy window
 * `[spanStart, spanEnd)`, as `{ offset, steps }` re-based to the window start (the same
 * basis as the lane's events). Read straight off the `Score` value via
 * `restShiftOverrideOf`. See docs/rest-shift-plan.md §6.5.
 */
function restShiftsInWindow(
  score: Score,
  staff: number,
  voice: number,
  spanStart: Fraction,
  spanEnd: Fraction,
): Array<{ offset: Fraction; steps: number }> {
  const starts = measureStartOffsets(score)
  const staffId = keyStaffId(score, staff) // this lane's staff → key segment (undefined for staff 0)
  const out: Array<{ offset: Fraction; steps: number }> = []
  for (const m of [...score.measures].sort((a, b) => a.number - b.number)) {
    const mStart = starts.get(m.number)
    if (!mStart) continue
    for (const n of getMeasureNotes(m, score)) {
      if (!n.isRest || voiceOf(n) !== voice || staffOf(n) !== staff) continue
      const abs = fracAdd(mStart, n.beat)
      if (!(fracGte(abs, spanStart) && fracLt(abs, spanEnd))) continue
      const ov = restShiftOverrideOf(score, restPositionKey(m.id, voice, n.beat, staffId))
      if (!ov) continue
      out.push({ offset: fracSub(abs, spanStart), steps: ov.steps })
    }
  }
  return out
}

/**
 * Hidden rests of one `(staff, voice)` lane whose onset falls inside the copy window
 * `[spanStart, spanEnd)`, as `{ offset }` re-based to the window start (same basis as the
 * lane's events). The hidden twin of {@link restShiftsInWindow}. See docs/rest-hide-plan.md.
 */
function restHiddenInWindow(
  score: Score,
  staff: number,
  voice: number,
  spanStart: Fraction,
  spanEnd: Fraction,
): Array<{ offset: Fraction }> {
  const starts = measureStartOffsets(score)
  const staffId = keyStaffId(score, staff) // this lane's staff → key segment (undefined for staff 0)
  const out: Array<{ offset: Fraction }> = []
  for (const m of [...score.measures].sort((a, b) => a.number - b.number)) {
    const mStart = starts.get(m.number)
    if (!mStart) continue
    for (const n of getMeasureNotes(m, score)) {
      if (!n.isRest || voiceOf(n) !== voice || staffOf(n) !== staff) continue
      const abs = fracAdd(mStart, n.beat)
      if (!(fracGte(abs, spanStart) && fracLt(abs, spanEnd))) continue
      if (!restHiddenOf(score, restPositionKey(m.id, voice, n.beat, staffId))) continue
      out.push({ offset: fracSub(abs, spanStart) })
    }
  }
  return out
}

/**
 * Note horizontal offsets (client #12) of one `(staff, voice)` lane whose slot onset falls inside
 * the copy window `[spanStart, spanEnd)`, as `{ offset, x }` re-based to the window start (same basis
 * as the lane's events). The chord/rest twin of {@link restShiftsInWindow} — it walks SLOTS (a note
 * offset hangs off the whole slot, chord or rest), matching the slot's own `staffId`/`voice`.
 */
function noteOffsetsInWindow(
  score: Score,
  staff: number,
  voice: number,
  spanStart: Fraction,
  spanEnd: Fraction,
): Array<{ offset: Fraction; x: number; member?: number }> {
  const starts = measureStartOffsets(score)
  const out: Array<{ offset: Fraction; x: number; member?: number }> = []
  for (const m of [...score.measures].sort((a, b) => a.number - b.number)) {
    const mStart = starts.get(m.number)
    if (!mStart) continue
    for (const s of m.slots) {
      if (voiceOf(s) !== voice || staffIndexOfId(score, s.staffId) !== staff) continue
      const abs = fracAdd(mStart, s.beat)
      if (!(fracGte(abs, spanStart) && fracLt(abs, spanEnd))) continue
      const offset = fracSub(abs, spanStart)
      const ov = noteOffsetOverrideOf(score, s.id)
      if (ov && ov.x !== 0) out.push({ offset, x: ov.x })
      // ⭐ …and each fanned MEMBER's own, at the group's offset plus its place in the group. The
      // member ids on the far side are freshly minted (`cloneFanFresh`), so the index is the address
      // — safe here because a copy and its paste are one passage, in order.
      if (s.type !== 'chord' || !s.fan?.members) continue
      s.fan.members.forEach((pitches, k) => {
        const id = pitches[0]?.id
        if (!id) return
        const mov = noteOffsetOverrideOf(score, id)
        if (mov && mov.x !== 0) out.push({ offset, x: mov.x, member: k + 1 })
      })
    }
  }
  return out
}

/**
 * Two-note tremolos fully inside the copy window — the FIRST note's offset, plus its stroke style.
 *
 * "Fully" is the whole rule: a pair is a RELATION between two slots, so it travels only when BOTH
 * are in the selection. Copying just the first note copies a note, not half a mark — which is the
 * plan's own wording for what must NOT travel.
 *
 * Validated here as well as on paste, so a stale flag in the source (one that draw-time validation is
 * already refusing to draw) is never what gets copied.
 */
function tremoloPairsInWindow(
  score: Score,
  staff: number,
  voice: number,
  spanStart: Fraction,
  spanEnd: Fraction,
): Array<{ offset: Fraction; style?: 'joined' | 'open' }> {
  const starts = measureStartOffsets(score)
  const out: Array<{ offset: Fraction; style?: 'joined' | 'open' }> = []
  for (const m of [...score.measures].sort((a, b) => a.number - b.number)) {
    const mStart = starts.get(m.number)
    if (!mStart) continue
    for (const slot of m.slots) {
      if (slot.type !== 'chord' || !slot.tremoloPair) continue
      if (voiceOf(slot) !== voice || staffIndexOfId(score, slot.staffId) !== staff) continue
      const lane = laneOfSlot(m.slots, slot)
      const index = lane.indexOf(slot)
      if (!pairIsValid(lane, index)) continue
      const abs = fracAdd(mStart, slot.beat)
      const partnerAbs = fracAdd(mStart, lane[index + 1].beat)
      // BOTH ends inside, or it is not a pair to copy.
      if (!(fracGte(abs, spanStart) && fracLt(partnerAbs, spanEnd))) continue
      out.push({ offset: fracSub(abs, spanStart), ...(slot.tremoloPairStyle ? { style: slot.tremoloPairStyle } : {}) })
    }
  }
  return out
}

/**
 * User-authored leading spaces (client #10) whose column falls inside the copy window
 * `[spanStart, spanEnd)`, re-based to the window start. The system-wide sibling of
 * {@link restShiftsInWindow}: no staff and no voice, because a space addresses the column.
 *
 * Read straight off the `Score` value via `measureLeadingSpaces`, so it sees every space in the
 * window whether or not the note under it happened to be selected — the selection defines a
 * musical WINDOW here, not a set of elements.
 */
function leadingSpacesInWindow(
  score: Score,
  spanStart: Fraction,
  spanEnd: Fraction,
): Array<{ offset: Fraction; space: number }> {
  const starts = measureStartOffsets(score)
  const out: Array<{ offset: Fraction; space: number }> = []
  for (const m of [...score.measures].sort((a, b) => a.number - b.number)) {
    const mStart = starts.get(m.number)
    if (!mStart) continue
    for (const { beat, space } of measureLeadingSpaces(score, m.id)) {
      const abs = fracAdd(mStart, beat)
      if (!(fracGte(abs, spanStart) && fracLt(abs, spanEnd))) continue
      out.push({ offset: fracSub(abs, spanStart), space })
    }
  }
  return out
}

/**
 * The `(staff, voice)` pairs that contain at least one selected note, grouped as
 * `staff → sorted voices`. This is the lane spine: one lane per selected staff×voice.
 * `score` is threaded into getMeasureNotes so the staff projection isn't dropped.
 */
function selectedStaffVoices(score: Score, noteIds: Set<string>): Map<number, number[]> {
  const raw = new Map<number, Set<number>>()
  for (const m of score.measures) {
    for (const n of getMeasureNotes(m, score)) {
      if (!noteIds.has(n.id)) continue
      const staff = staffOf(n)
      if (!raw.has(staff)) raw.set(staff, new Set())
      raw.get(staff)!.add(voiceOf(n))
    }
  }
  const out = new Map<number, number[]>()
  for (const [staff, voices] of raw) out.set(staff, [...voices].sort((a, b) => a - b))
  return out
}

/**
 * Dynamics whose position falls FULLY inside the copy window `[spanStart, spanEnd)` and whose
 * staff is within the copied staff span `[topStaff, maxStaff]`, as {@link ClipDynamic}s with
 * the staff re-based to `topStaff` (relative) and the offset re-based to the window start.
 * Straddling / out-of-band dynamics are left behind (decision: fully-enclosed-only).
 */
function dynamicsInWindow(
  score: Score,
  topStaff: number,
  maxStaff: number,
  spanStart: Fraction,
  spanEnd: Fraction,
): ClipDynamic[] {
  const starts = measureStartOffsets(score)
  const out: ClipDynamic[] = []
  for (const m of [...score.measures].sort((a, b) => a.number - b.number)) {
    const mStart = starts.get(m.number)
    if (!mStart) continue
    for (const d of m.dynamics ?? []) {
      const abs = fracAdd(mStart, d.beat)
      if (!(fracGte(abs, spanStart) && fracLt(abs, spanEnd))) continue
      const staffIdx = staffIndexOfId(score, d.staffId)
      if (staffIdx < topStaff || staffIdx > maxStaff) continue
      const off = dynamicOffsetOverrideOf(score, d.id)
      out.push({
        staff: staffIdx - topStaff,
        voice: voiceOf(d),
        offset: fracSub(abs, spanStart),
        text: d.text,
        ...(d.placement !== undefined ? { placement: d.placement } : {}),
        ...(off ? { engravingOffset: { x: off.x, y: off.y } } : {}),
      })
    }
  }
  return out
}

/**
 * Slurs with BOTH endpoints fully inside the copy window `[spanStart, spanEnd)` and on staves
 * within the copied span, as {@link ClipSlur}s: each endpoint addressed by relative staff /
 * voice / offset / pitch so paste can re-find the freshly-pasted note. A slur with an endpoint
 * outside the window is left behind (decision: fully-enclosed-only).
 */
function slursInWindow(
  score: Score,
  topStaff: number,
  maxStaff: number,
  spanStart: Fraction,
  spanEnd: Fraction,
): ClipSlur[] {
  const slurs = score.slurs
  if (!slurs || slurs.length === 0) return []

  // Endpoint note id → its absolute onset / staff / voice / pitch (non-rest notes only).
  type EP = { abs: Fraction; staff: number; voice: number; pitch: ClipSlurPitch }
  const info = new Map<string, EP>()
  const starts = measureStartOffsets(score)
  for (const m of [...score.measures].sort((a, b) => a.number - b.number)) {
    const mStart = starts.get(m.number)
    if (!mStart) continue
    for (const n of getMeasureNotes(m, score)) {
      if (n.isRest || n.step === undefined || n.octave === undefined) continue
      info.set(n.id, {
        abs: fracAdd(mStart, n.beat),
        staff: staffOf(n),
        voice: voiceOf(n),
        pitch: { step: n.step, alter: n.alter ?? 0, octave: n.octave },
      })
    }
  }

  const enclosed = (e: EP | undefined): e is EP =>
    !!e && fracGte(e.abs, spanStart) && fracLt(e.abs, spanEnd) && e.staff >= topStaff && e.staff <= maxStaff

  const out: ClipSlur[] = []
  for (const slur of slurs) {
    const s = info.get(slur.startNoteId)
    const e = info.get(slur.endNoteId)
    if (!enclosed(s) || !enclosed(e)) continue
    out.push({
      startStaff: s.staff - topStaff, startVoice: s.voice, startOffset: fracSub(s.abs, spanStart), startPitch: s.pitch,
      endStaff: e.staff - topStaff, endVoice: e.voice, endOffset: fracSub(e.abs, spanStart), endPitch: e.pitch,
      ...(slur.placement !== undefined ? { placement: slur.placement } : {}),
    })
  }
  return out
}

/**
 * Build a {@link ClipboardPayload} from a note selection. Copies the contiguous
 * musical span from the first to the last selected note (so a Shift range copies
 * exactly; a scattered Ctrl selection copies the whole span between its endpoints,
 * with the in-between content included). Ties and tuplets come out correct because
 * the span is taken from {@link flattenRegion}'s event stream.
 *
 * Multi-voice AND multi-staff aware: every `(staff, voice)` lane that holds a selected note
 * is captured in its own stream (sliced to the same window), so a passage spanning voices 1
 * and 2 or staves 1 and 2 copies all of them. Staves are stored RELATIVE to the topmost
 * copied staff (0 = topmost), so a staves-1+2 clip can paste onto staves 3+4. Returns null
 * when nothing usable is selected.
 */
export function buildClipboardFromSelection(score: Score, noteIds: string[]): ClipboardPayload | null {
  const idSet = new Set(noteIds)
  const spans = selectedSpans(score, idSet)
  if (spans.length === 0) return null

  const spanStart = spans.reduce((a, s) => (fracCompare(s.start, a) < 0 ? s.start : a), spans[0].start)
  const spanEnd = spans.reduce((a, s) => (fracCompare(s.end, a) > 0 ? s.end : a), spans[0].end)
  const spanBeats = fracSub(spanEnd, spanStart)

  // One lane per selected (staff, voice). Staves are re-based to the topmost selected staff so
  // the clip stores RELATIVE offsets: staff 1+2 → relStaff 0+1, paste-able onto any base staff.
  // Each lane is captured by narrowing the score to its own staff (staffMeasureView) before the
  // flatten — otherwise the per-voice flatten merges every staff's notes into one stream.
  const staffVoices = selectedStaffVoices(score, idSet)
  const staves = [...staffVoices.keys()].sort((a, b) => a - b)
  const topStaff = staves[0]
  const spanStaves = staves[staves.length - 1] - topStaff + 1

  const orderedMeasures = [...score.measures].sort((a, b) => a.number - b.number)
  const lanes: ClipboardLane[] = []
  for (const staff of staves) {
    const staffId = staffIdAtIndex(score, staff)
    const ordered = orderedMeasures.map((m) => staffMeasureView(m, staffId, score))
    for (const v of staffVoices.get(staff)!) {
      const restShifts = restShiftsInWindow(score, staff, v, spanStart, spanEnd)
      const restHidden = restHiddenInWindow(score, staff, v, spanStart, spanEnd)
      const noteOffsets = noteOffsetsInWindow(score, staff, v, spanStart, spanEnd)
      const tremoloPairs = tremoloPairsInWindow(score, staff, v, spanStart, spanEnd)
      lanes.push({
        staff: staff - topStaff,
        voice: v,
        events: flattenRegion(ordered, v as 0 | 1 | 2 | 3)
          .filter((e) => fracGte(e.offset, spanStart) && fracLt(e.offset, spanEnd))
          .map((e) => ({ ...e, offset: fracSub(e.offset, spanStart) })),
        // Omit each key entirely when empty (clean payload / old-clip parity).
        ...(restShifts.length ? { restShifts } : {}),
        ...(restHidden.length ? { restHidden } : {}),
        ...(noteOffsets.length ? { noteOffsets } : {}),
        ...(tremoloPairs.length ? { tremoloPairs } : {}),
      })
    }
  }
  // Usable if any lane carries note events OR a shifted/hidden rest OR an offset (a lone one still copies).
  if (lanes.every((l) => l.events.length === 0 && !l.restShifts?.length && !l.restHidden?.length && !l.noteOffsets?.length)) return null

  // Dynamics (Phase 2) and slurs (Phase 3) fully inside the window travel too, staff re-based
  // to the topmost copied staff.
  const dynamics = dynamicsInWindow(score, topStaff, staves[staves.length - 1], spanStart, spanEnd)
  const slurs = slursInWindow(score, topStaff, staves[staves.length - 1], spanStart, spanEnd)
  // Authored spaces in the window travel too (client #10) — no staff re-basing, since a space
  // has no staff.
  const spaces = leadingSpacesInWindow(score, spanStart, spanEnd)

  // Origin = the (measure, beat) of the earliest selected note, for reference.
  const starts = measureStartOffsets(score)
  let origin = { measure: score.measures[0].number, beat: fracCreate(0, 1) }
  outer: for (const m of score.measures) {
    const mStart = starts.get(m.number)
    if (!mStart) continue
    for (const n of getMeasureNotes(m)) {
      if (idSet.has(n.id) && fracCompare(fracAdd(mStart, n.beat), spanStart) === 0) {
        origin = { measure: m.number, beat: n.beat }
        break outer
      }
    }
  }

  return {
    format: 'opus-editor/clipboard', version: 3, origin, spanBeats, spanStaves, lanes, dynamics, slurs,
    // Omitted entirely when empty, matching `restShifts` (clean payload / old-clip parity).
    ...(spaces.length ? { spaces } : {}),
  }
}

/** The (measure, beat, voice, staff) of the earliest note in a selection — the paste target
 *  when pasting onto a selection (overwrite-forward from the selection start). The voice/staff
 *  are the paste destination for a single-voice/single-staff clip. `score` is threaded into
 *  getMeasureNotes so the staff projection isn't silently dropped (the two-projection gotcha). */
export function earliestSelectedPosition(
  score: Score,
  noteIds: string[],
): { measure: number; beat: Fraction; voice: number; staff: number } | null {
  const idSet = new Set(noteIds)
  const starts = measureStartOffsets(score)
  let best: { measure: number; beat: Fraction; voice: number; staff: number; abs: Fraction } | null = null
  for (const m of score.measures) {
    const mStart = starts.get(m.number)
    if (!mStart) continue
    for (const n of getMeasureNotes(m, score)) {
      if (!idSet.has(n.id)) continue
      const abs = fracAdd(mStart, n.beat)
      if (!best || fracCompare(abs, best.abs) < 0) {
        best = { measure: m.number, beat: n.beat, voice: voiceOf(n), staff: staffOf(n), abs }
      }
    }
  }
  return best ? { measure: best.measure, beat: best.beat, voice: best.voice, staff: best.staff } : null
}

/** A short human-readable line for the copy/paste console dump. */
export function clipboardSummary(p: ClipboardPayload): string {
  const total = p.lanes.reduce((a, l) => a + l.events.length, 0)
  const perLane = p.lanes.map((ln) => {
    const parts = ln.events.map((e) => {
      if (e.atomic) return '[tuplet]'
      const pitches = (e.pitches ?? []).map((pt) => formatPitch(pt)).join('+')
      return `[${pitches || 'rest'} ${fracToNumber(e.duration)}b @${fracToNumber(e.offset)}]`
    })
    return `s${ln.staff}v${ln.voice + 1}: ${parts.join(' ') || '(empty)'}`
  })
  const dyn = p.dynamics.length ? `, ${p.dynamics.length} dynamic(s)` : ''
  const slr = p.slurs.length ? `, ${p.slurs.length} slur(s)` : ''
  return `${total} event(s) across ${p.lanes.length} lane(s) / ${p.spanStaves} staff(s)${dyn}${slr}, span ${fracToNumber(p.spanBeats)}b — ${perLane.join(' | ')}`
}
